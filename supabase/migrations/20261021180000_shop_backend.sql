-- PC-DEC-074/076: Weapon shop backend
-- Adds shop config to game_config, a per-player shop_stock table, and reroll
-- tracking columns on profiles. Idempotent (IF NOT EXISTS) so re-run is safe.

-- 1. Shop tunables on the single-row game_config table
ALTER TABLE public.game_config
  ADD COLUMN IF NOT EXISTS reroll_base_price integer NOT NULL DEFAULT 50,
  ADD COLUMN IF NOT EXISTS reroll_price_multiplier numeric NOT NULL DEFAULT 2.0,
  ADD COLUMN IF NOT EXISTS ap_reset_cost integer NOT NULL DEFAULT 10,
  ADD COLUMN IF NOT EXISTS sell_recovery_rate numeric NOT NULL DEFAULT 0.42,
  ADD COLUMN IF NOT EXISTS shop_refresh_hour integer NOT NULL DEFAULT 0;

COMMENT ON COLUMN public.game_config.reroll_base_price IS 'Base gold cost of the first shop reroll.';
COMMENT ON COLUMN public.game_config.reroll_price_multiplier IS 'Exponential multiplier per reroll: cost = base * mult^count.';
COMMENT ON COLUMN public.game_config.ap_reset_cost IS 'AP cost to reset the shop reroll counter to 0.';
COMMENT ON COLUMN public.game_config.sell_recovery_rate IS 'Fraction of buy price returned on sell (anti-arbitrage).';
COMMENT ON COLUMN public.game_config.shop_refresh_hour IS 'UTC hour of the daily shop stock refresh (0 = 00:00 GMT).';

-- 2. Per-player daily shop stock (2 weapons + 2 potions, slots 1-4)
CREATE TABLE IF NOT EXISTS public.shop_stock (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  slot integer NOT NULL CHECK (slot BETWEEN 1 AND 4),
  kind text NOT NULL CHECK (kind IN ('weapon','consumable')),
  template_id bigint NOT NULL,
  name text,
  stock_date date NOT NULL,
  -- denormalized rolled stats (weapons)
  damage integer,
  speed integer,
  accuracy integer,
  crit_chance integer,
  quality_multiplier numeric,
  tier text,
  -- denormalized rolled stats (consumables)
  rolled_floor integer,
  rolled_window integer,
  rolled_speed integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, slot, stock_date)
);

COMMENT ON TABLE public.shop_stock IS 'Per-player daily shop inventory. Rolled at daily refresh (00:00 GMT).';

-- 3. Reroll tracking on profiles
ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS shop_stock_date date,
  ADD COLUMN IF NOT EXISTS shop_reroll_count integer NOT NULL DEFAULT 0;

COMMENT ON COLUMN public.profiles.shop_stock_date IS 'UTC date the current shop stock was rolled for this player.';
COMMENT ON COLUMN public.profiles.shop_reroll_count IS 'Number of rerolls this shop day; resets on daily refresh.';

-- 4. RLS: shop_stock is owner-only
ALTER TABLE public.shop_stock ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'shop_stock' AND policyname = 'shop_stock_owner_select') THEN
    CREATE POLICY shop_stock_owner_select ON public.shop_stock FOR SELECT USING (auth.uid() = user_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'shop_stock' AND policyname = 'shop_stock_owner_insert') THEN
    CREATE POLICY shop_stock_owner_insert ON public.shop_stock FOR INSERT WITH CHECK (auth.uid() = user_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'shop_stock' AND policyname = 'shop_stock_owner_delete') THEN
    CREATE POLICY shop_stock_owner_delete ON public.shop_stock FOR DELETE USING (auth.uid() = user_id);
  END IF;
END $$;